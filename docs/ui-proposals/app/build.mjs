// Builds ../peta-prototype.html: one self-contained file (CSS, JS and optimized art inlined as data: URIs) that opens
// from file:// and can be published as-is. Needs ImageMagick (`convert`). Run from anywhere: node docs/ui-proposals/app/build.mjs
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const art = path.resolve(here, "../../../src/art");
const out = path.resolve(here, "../peta-prototype.html");

const assetsSrc = fs.readFileSync(path.join(here, "js/assets.js"), "utf8");
const P = new Function("return " + assetsSrc.match(/const P = (\{[\s\S]*?\n\});/)[1])();

// [pattern, max box, quality]
const RULES = [
  [/^samples\//, "560x560", 84], [/^pack\//, "620x830", 86], [/^tabs\//, "320x128", 88], [/^ui\/(seal|button)/, "480x140", 88], [/^ui\/material-tray/, "840x300", 84], [/^ui\/(card-locked|memo|index)/, "560x380", 84], [/^ui\/tag/, "300x370", 86], [/^ui\/(paper-clip|binder)/, "160x160", 86], [/^book\/(cover-board|page-paper)/, "640x640", 70], [/^today\/(choice|material-card)/, "360x360", 86], [/^today\/envelope|^today\/foil/, "640x430", 86],
  [/^print\/backing/, "520x780", 84], [/^book\/page-curl/, "900x640", 70], [/^back\/paper/, "700x700", 76], [/^book\/page-right/, "1100x800", 72], [/^creator\/cutting-mat/, "1700x850", 74],
  [/^book\/cover/, "800x550", 80], [/^gift\/mystery/, "420x420", 86], [/^gift\/note/, "520x330", 84], [/^arrival/, "480x340", 86], [/^empty|^onboarding/, "640x420", 80],
];
const mime = (f) => (f.endsWith(".svg") ? "image/svg+xml" : f.endsWith(".jpg") ? "image/jpeg" : "image/webp");
function encode(file) {
  const abs = path.join(art, file);
  if (file.endsWith(".svg")) return `data:image/svg+xml;base64,${fs.readFileSync(abs).toString("base64")}`;
  const rule = RULES.find(([re]) => re.test(file));
  const jpg = file.endsWith(".jpg");
  const args = [abs, "-background", "none", ...(rule ? ["-resize", rule[1] + ">"] : []), "-quality", String(rule ? rule[2] : 88)];
  if (jpg) args.push("-strip", "jpg:-"); else args.push("-define", "webp:alpha-quality=96", "-define", "webp:method=5", "webp:-");
  const buf = execFileSync("convert", args, { maxBuffer: 64 * 1024 * 1024 });
  return `data:${mime(jpg ? "x.jpg" : "x.webp")};base64,${buf.toString("base64")}`;
}
const A = {};
let total = 0;
for (const [k, f] of Object.entries(P)) { A[k] = encode(f); total += A[k].length; }
const assets = `/* generated by build.mjs */\nconst A = ${JSON.stringify(A)};\n`;

let html = fs.readFileSync(path.join(here, "index.html"), "utf8");
html = html.replace(/<link rel="stylesheet" href="(css\/[\w-]+\.css)" \/>\n?/g, (_, f) => `<style>\n${fs.readFileSync(path.join(here, f), "utf8")}\n</style>\n`);
html = html.replace(/<script src="(js\/[\w-]+\.js)"><\/script>\n?/g, (_, f) => `<script>\n${f === "js/assets.js" ? assets : fs.readFileSync(path.join(here, f), "utf8")}\n</script>\n`);
html = html.replace(/<title>[^<]*<\/title>/, "<title>Peta One Window</title>");
fs.writeFileSync(out, html);
// --fragment <path>: the same page without <!doctype>/<html>/<head>/<body>, for hosts that wrap the page themselves
const fi = process.argv.indexOf("--fragment");
if (fi > 0) {
  const body = html.match(/<body[^>]*>([\s\S]*)<\/body>/)[1];
  const head = html.match(/<head>([\s\S]*)<\/head>/)[1].replace(/<meta charset[^>]*>\n?|<meta name="viewport"[^>]*>\n?/g, "");
  fs.writeFileSync(path.resolve(process.argv[fi + 1]), head + "\n" + body);
}
console.log(`wrote ${path.relative(process.cwd(), out)}  ${(html.length / 1048576).toFixed(2)} MB  (art ${(total / 1048576).toFixed(2)} MB)`);
