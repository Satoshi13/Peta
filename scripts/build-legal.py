#!/usr/bin/env python3
"""Turn docs/legal/{terms,privacy}.md into the pages peta-api serves at /terms and /privacy (cloudflare/peta-api/src/legal.ts).

The effective date lives in docs/legal/effective-date.json ({"ja": "2026年10月20日", "en": "20 October 2026"}); until it
exists the pages say the date is to be announced. --check fails if legal.ts is out of date (used by the tests).
Only the Markdown these two documents use is supported: # and ## headings, paragraphs, - lists, | tables |, ---,
**bold** and `code`.
"""
import html, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEGAL = ROOT / 'docs/legal'
OUT = ROOT / 'cloudflare/peta-api/src/legal.ts'
TITLES = {'terms': 'Peta 利用規約 / Terms of Use', 'privacy': 'Peta プライバシーポリシー / Privacy Policy'}


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    return re.sub(r'`(.+?)`', r'<code>\1</code>', text)


def render(md):
    out, para, items, rows = [], [], [], []
    def flush():
        nonlocal para, items, rows
        if para:
            out.append('<p>' + '<br>'.join(inline(l) for l in para) + '</p>')
        if items:
            out.append('<ul>' + ''.join(f'<li>{inline(i)}</li>' for i in items) + '</ul>')
        if rows:
            head, body = rows[0], [r for r in rows[2:]]
            out.append('<div class="table"><table><thead><tr>' + ''.join(f'<th>{inline(c)}</th>' for c in head) + '</tr></thead><tbody>'
                       + ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in body) + '</tbody></table></div>')
        para, items, rows = [], [], []
    for line in md.splitlines():
        s = line.strip()
        if not s:
            flush(); continue
        if s == '---':
            flush(); out.append('<hr>'); continue
        if s.startswith('# '):
            flush(); out.append(f'<h1>{inline(s[2:])}</h1>'); continue
        if s.startswith('## '):
            flush(); out.append(f'<h2>{inline(s[3:])}</h2>'); continue
        if s.startswith('|'):
            if para or items: flush()
            rows.append([c.strip() for c in s.strip('|').split('|')]); continue
        if s.startswith('- '):
            if para or rows: flush()
            items.append(s[2:]); continue
        if items or rows: flush()
        para.append(s)
    flush()
    return '\n'.join(out)


STYLE = ('*{box-sizing:border-box}:root{--paper:#f8f4eb;--ink:#2b2a28;--muted:#6b655b;--line:#e2dbcc}'
         '@media(prefers-color-scheme:dark){:root{--paper:#22201d;--ink:#efe9de;--muted:#aaa293;--line:#3a3631}}'
         'body{margin:0;background:var(--paper);color:var(--ink);font:15px/1.8 -apple-system,BlinkMacSystemFont,"Hiragino Sans","Helvetica Neue",sans-serif}'
         'main{max-width:760px;margin:0 auto;padding:48px 20px 80px}h1{font-size:26px;line-height:1.3;letter-spacing:-.01em;margin:0 0 6px}'
         'h2{font-size:17px;margin:34px 0 8px}p,li{margin:0 0 12px}ul{padding-left:20px}hr{border:0;border-top:1px solid var(--line);margin:56px 0}'
         'code{font:13px ui-monospace,monospace}.table{overflow-x:auto}table{border-collapse:collapse;width:100%;font-size:14px;margin:6px 0 12px}'
         'th,td{border-bottom:1px solid var(--line);padding:8px 10px;text-align:left;vertical-align:top}th{color:var(--muted);font-weight:600}'
         '.mark{font:11px/1 ui-monospace,monospace;letter-spacing:.2em;color:var(--muted);margin:0 0 28px}')


def page(name, dates):
    md = (LEGAL / f'{name}.md').read_text()
    md = md.replace('{{EFFECTIVE_DATE}}', dates['ja']).replace('{{EFFECTIVE_DATE_EN}}', dates['en'])
    return ('<!doctype html><html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>{TITLES[name]}</title><style>{STYLE}</style></head><body><main><p class="mark">PETA</p>\n{render(md)}\n</main></body></html>\n')


def build():
    path = LEGAL / 'effective-date.json'
    dates = json.loads(path.read_text()) if path.exists() else {'ja': '未定(配布開始日に記載します)', 'en': 'to be announced (the first release day)'}
    pages = {name: page(name, dates) for name in ('terms', 'privacy')}
    return ('// Generated by scripts/build-legal.py from docs/legal/*.md. Edit the Markdown and run the script; do not edit here.\n'
            + ''.join(f'export const {name.upper()}_HTML = {json.dumps(text, ensure_ascii=False)};\n' for name, text in pages.items()))


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('cloudflare/peta-api/src/legal.ts is out of date. Run: python3 scripts/build-legal.py')
        print('legal.ts is up to date.')
    else:
        OUT.write_text(text)
        print(f'Wrote {OUT.relative_to(ROOT)}')
